/** Render ikon dari nama Material Symbols yang tersimpan di database. */
export function IkonLucide({
  nama,
  className,
}: {
  nama?: string | null;
  className?: string;
}) {
  // Pencarian langsung pada tabel (bukan lewat fungsi) agar detektor
  // react-hooks tidak menganggap komponen dibuat saat render.
  const Ikon = (nama && PETA_IKON[nama]) || Info;
  return <Ikon aria-hidden="true" className={className} />;
}
